package com.bm.copilot.copilot;

import static org.assertj.core.api.Assertions.assertThat;

import com.bm.copilot.TestcontainersConfiguration;
import com.bm.copilot.copilot.agent.CopilotOrchestrator;
import com.bm.copilot.knowledge.service.IngestionService;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/**
 * Real-model probe for clarifying questions, kept apart from Developer B's dataset. Each question goes through
 * the orchestrator twice, because the model can vary between runs even at temperature 0.
 * Run with: ./mvnw test -Dtest=ClarificationProbeTest -Deval=true
 */
@SpringBootTest
@Import({TestcontainersConfiguration.class, CopilotEvaluationTest.CachedEmbedderConfiguration.class})
@EnabledIfSystemProperty(named = "eval", matches = "true")
class ClarificationProbeTest {

    private static final int RUNS = 2;
    private static final long PAUSE_BETWEEN_QUESTIONS_MS = 4000;

    private record Probe(String question, boolean ambiguous) {
    }

    private static final List<Probe> PROBES = List.of(
            new Probe("What is the card limit?", true),
            new Probe("What is the interest rate?", true),
            new Probe("What documents does the customer need?", true),
            new Probe("What are the debit and credit card replacement fees?", false),
            new Probe("How many wrong PIN attempts block a card?", false),
            new Probe("How many days does a customer have to file a card dispute?", false));

    @Autowired
    IngestionService ingestionService;

    @Autowired
    CopilotOrchestrator orchestrator;

    @DynamicPropertySource
    static void geminiKey(DynamicPropertyRegistry registry) {
        String key = CopilotEvaluationTest.readGeminiKey();
        registry.add("spring.ai.google.genai.api-key", () -> key);
        registry.add("spring.ai.google.genai.embedding.api-key", () -> key);
    }

    @Test
    void ambiguousQuestionsAskAndClearQuestionsAnswer() throws Exception {
        ingestCorpus();

        StringBuilder md = new StringBuilder("""
                # Clarifying-question probe

                Generated by `ClarificationProbeTest` (real Gemini model, through the orchestrator, %d runs).
                Expected: ambiguous questions ask for the missing detail; clear questions are answered with citations.

                | Question | Kind | Run | Outcome | Response |
                |---|---|---|---|---|
                """.formatted(RUNS));
        int asExpected = 0;
        for (int run = 1; run <= RUNS; run++) {
            for (Probe probe : PROBES) {
                AskResponse response = orchestrator.ask(probe.question());
                Thread.sleep(PAUSE_BETWEEN_QUESTIONS_MS);

                assertThat(response.answer()).as(probe.question()).isNotBlank();
                String outcome = response.needsClarification() ? "ASKED"
                        : response.refused() ? "REFUSED" : "ANSWERED";
                boolean expected = probe.ambiguous() ? outcome.equals("ASKED") : outcome.equals("ANSWERED");
                if (expected) {
                    asExpected++;
                }
                md.append("| ").append(probe.question())
                        .append(" | ").append(probe.ambiguous() ? "ambiguous" : "clear")
                        .append(" | ").append(run)
                        .append(" | ").append(outcome).append(expected ? "" : " (unexpected)")
                        .append(" | ").append(response.answer().replace("|", "/").replace("\n", " "))
                        .append(" |\n");
            }
        }
        md.append("\nAs expected: ").append(asExpected).append('/').append(RUNS * PROBES.size()).append('\n');
        Files.writeString(Path.of("eval/clarification-probe.md"), md.toString(), StandardCharsets.UTF_8);
    }

    private void ingestCorpus() throws Exception {
        List<Path> files;
        try (Stream<Path> docs = Files.list(Path.of("docs")); Stream<Path> docsSrc = Files.list(Path.of("docs-src"))) {
            files = Stream.concat(docs, docsSrc).sorted().toList();
        }
        for (Path file : files) {
            ingestionService.ingest(file.getFileName().toString(), Files.readAllBytes(file));
        }
    }
}
